    zipcode varchar(5) not null,
    city varchar(255) not null,
    state varchar(255) not null,
    street varchar(255) not null,
    detail varchar(255),
    latitude numeric(10,7) not null,
    longitude numeric(10,7) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table tasks (
    id bigint generated by default as identity,
    dtype varchar(255) not null,
    status varchar(255) not null,
    start_date date not null,
    end_date date not null,
    worker_id bigint references members(id),
    worker_title varchar(255),
    worker_memo varchar(255),
    worker_company varchar(255),
    zipcode varchar(5),
    city varchar(255),
    state varchar(255),
    street varchar(255),
    detail varchar(255),
    latitude numeric(10,7),
    longitude numeric(10,7),
    project_id bigint references projects(id),
    project_title varchar(255),
    project_requirement varchar(255),
    project_memo varchar(255),
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table task_trades (
    task_id bigint not null references tasks(id),
    trade varchar(255)
);

create table offers (
    id bigint generated by default as identity,
    task_id bigint not null references tasks(id),
    worker_id bigint not null references members(id),
    seq integer not null,
    due date not null,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table posts (
    id bigint generated by default as identity,
    member_id bigint not null references members(id),
    task_id bigint references tasks(id),
    content TEXT,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table credentials (
    id bigint generated by default as identity,
    member_id bigint not null references members(id),
    type varchar(255) not null,
    status varchar(255) not null,
    expired_at date,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table coworkers (
    id bigint generated by default as identity,
    min_id bigint not null references members(id),
    max_id bigint not null references members(id),
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_coworkers_members on coworkers(min_id, max_id) where deleted_at is null;

create table coworker_requests (
    id bigint generated by default as identity,
    from_id bigint not null references members(id),
    to_id bigint not null references members(id),
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_coworker_requests_members on coworker_requests(from_id, to_id) where deleted_at is null;

create table recommendations (
    id bigint generated by default as identity,
    from_id bigint not null references members(id),
    to_id bigint not null references members(id),
    content TEXT not null,
    visible boolean not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_recommendations_from_to on recommendations(from_id, to_id) where deleted_at is null;

create table drives (
    id bigint generated by default as identity,
    dtype varchar(255) not null,
    project_id bigint references projects(id),
    member_id bigint references members(id),
    title varchar(255) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table drive_members (
    id bigint generated by default as identity,
    drive_id bigint not null references drives(id),
