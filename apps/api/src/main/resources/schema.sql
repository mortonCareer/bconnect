create table otps (
    id bigint generated by default as identity,
    phone varchar(255) not null,
    code varchar(255) not null,
    code_expired_at timestamp(6) not null,
    attempts integer not null,
    code_revoked boolean not null,
    token varchar(255),
    token_expired_at timestamp(6),
    token_revoked boolean,
    daily_count integer not null,
    last_sent_at timestamp(6) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table members (
    id bigint generated by default as identity,
    username varchar(255) not null,
    name varchar(255) not null,
    phone varchar(255) not null,
    role varchar(255) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_members_username on members(username) where deleted_at is null;
create unique index udx_members_phone on members(phone) where deleted_at is null;

create table sessions (
    id bigint generated by default as identity,
    member_id bigint not null references members(id),
    agent varchar(255) not null,
    ip varchar(255) not null,
    refresh_token varchar(255) not null,
    revoked boolean not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_sessions_member on sessions(member_id) where deleted_at is null;

create table attachments (
    id bigint generated by default as identity,
    member_id bigint not null references members(id),
    type varchar(255) not null,
    status varchar(255) not null,
    context varchar(255) not null,
    context_id bigint not null,
    reference_type varchar(255),
    reference_id bigint,
    uuid varchar(255) not null,
    stem varchar(255) not null,
    ext varchar(255) not null,
    content_type varchar(255) not null,
    size bigint not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_attachments_uuid on attachments(uuid) where deleted_at is null;

create table group_chats (
    id bigint generated by default as identity,
    title varchar(255) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table direct_chats (
    id bigint generated by default as identity,
    min_id bigint not null references members(id),
    max_id bigint not null references members(id),
    min_last_idx bigint not null,
    max_last_idx bigint not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_direct_chats_members on direct_chats(min_id, max_id) where deleted_at is null;

create table participants (
    id bigint generated by default as identity,
    chat_id bigint not null references group_chats(id),
    member_id bigint not null references members(id),
    last_idx bigint not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table messages (
    id bigint generated by default as identity,
    chat_id bigint not null,
    chat_type varchar(255) not null,
    member_id bigint not null references members(id),
    type varchar(255) not null,
    content TEXT not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);

create table profiles (
    id bigint generated by default as identity,
    member_id bigint not null references members(id),
    role varchar(255) not null,
    primary_trade varchar(255) not null,
    experience integer not null,
    headline varchar(255),
    about TEXT,
    zipcode varchar(5) not null,
    city varchar(255) not null,
    state varchar(255) not null,
    street varchar(255) not null,
    detail varchar(255),
    latitude numeric(10,7) not null,
    longitude numeric(10,7) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
    primary key (id)
);
create unique index udx_profiles_member on profiles(member_id) where deleted_at is null;

create table profile_trades (
    profile_id bigint not null references profiles(id),
    trade varchar(255)
);

create table companies (
    id bigint generated by default as identity,
    member_id bigint not null references members(id),
    name varchar(255) not null,
    brn varchar(255) not null,
    created_at timestamp(6) not null,
    modified_at timestamp(6) not null,
    deleted_at timestamp,
