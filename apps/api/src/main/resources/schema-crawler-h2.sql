create table if not exists kiscon_registration (
    ncr_gs_seq bigint,
    biz_reg_no TEXT not null,
    company_name TEXT,
    representative TEXT,
    trade_name TEXT,
    trade_reg_no TEXT,
    address TEXT,
    region TEXT,
    region_detail TEXT,
    reg_date integer,
    announce_date integer,
    flag TEXT,
    phone TEXT,
    synced_at timestamp(6) with time zone not null default current_timestamp,
    primary key (ncr_gs_seq)
);
create index if not exists idx_kiscon_reg_biz_no on kiscon_registration(biz_reg_no);

